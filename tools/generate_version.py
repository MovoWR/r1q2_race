"""Generate the client identity without changing Git or rewriting unchanged output."""
import argparse
import os
from pathlib import Path
import subprocess


def generate(source):
    def git(*args):
        return subprocess.check_output(["git", "-C", str(source), *args], stderr=subprocess.DEVNULL, text=True, env={**os.environ, "GIT_OPTIONAL_LOCKS": "0"}).strip()
    revision, commit, modified = "unknown", "unknown", ""
    number = 0
    try:
        # Do not accidentally identify a source archive using its parent repository.
        if Path(git("rev-parse", "--show-toplevel")).resolve() != source.resolve():
            raise ValueError("not the source repository")
        commit = git("rev-parse", "--short=12", "HEAD")
        if git("rev-parse", "--is-shallow-repository") == "false":
            number = int(git("rev-list", "--count", "HEAD"))
            revision = str(number)
        if git("status", "--porcelain", "--untracked-files=normal"):
            modified = " [modified]"
            commit += "-dirty"
    except (OSError, subprocess.CalledProcessError, ValueError):
        revision, commit, modified, number = "unknown", "unknown", "", 0
    return ('/* Generated by tools/generate_version.py. */\n'
            f'#define RACE_REVISION "{revision}"\n'
            f'#define RACE_COMMIT "{commit}"\n'
            f'#define RACE_MODIFIED "{modified}"\n'
            f'#define RACE_FILE_VERSION 0,{(number >> 16) & 65535},{number & 65535},0\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    content = generate(args.source)
    if not args.output.exists() or args.output.read_text() != content:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
